def get_next_topic():
    """获取下一篇不重复的爆款文案"""
    used_ids = []
    if os.path.exists(FILE_HISTORY):
        try:
            with open(FILE_HISTORY, "r", encoding="utf-8") as f:
                used_ids = json.load(f)
        except Exception:
            used_ids = []

    # 筛选未使用的文案
    unused_topics = [t for t in TOPIC_DATABASE if t["id"] not in used_ids]

    # 如果所有文案都已使用过一轮，重置历史开始新一轮（保持持续更新）
    if not unused_topics:
        print(">> [提示] 文案库已完整轮换一轮，正在开启全新一轮轮播循环...")
        used_ids = []
        unused_topics = TOPIC_DATABASE[:]

    # 随机抽取一篇未使用的文案
    selected = random.choice(unused_topics)
    used_ids.append(selected["id"])

    # 更新历史记录
    try:
        with open(FILE_HISTORY, "w", encoding="utf-8") as f:
            json.dump(used_ids, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"[!] 写入文案历史记录失败: {e}")

    return selected

